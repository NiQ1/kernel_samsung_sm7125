#!/usr/bin/env bash
#
# build_usb_fix_module.sh - generate a flashable KernelSU module that fixes the
# UN1CA "USB charge-only / options greyed out after boot" problem.
#
# Root cause (confirmed on a52q, 4.14.357-openela, UN1CA):
#   At boot the USB composite gadget never binds to the UDC. The boot config is
#   "sec_charging,adb", but adbd/FunctionFS isn't ready (sys.usb.ffs.ready=0), so
#   the gadget pullup is deferred and never retried. UsbDeviceManager's boot pass
#   runs trySetEnabledFunctions(forceRestart=false), decides the state already
#   matches, and never re-applies the config to configfs. Result:
#     /config/usb_gadget/g1/UDC is empty  ->  no function driver  ->  charge only,
#   with all USB mode options greyed out. The symptom also occurs on the stock
#   UN1CA kernel and not in recovery, i.e. it is a ROM/userspace init race, not a
#   kernel-config gap (F_MTP etc. are all present).
#
#   Toggling USB debugging "fixes" it because UsbDeviceManager then runs a full
#   restart (setUsbConfig(none) -> setUsbConfig(<fn>)) which rebinds the UDC.
#
# What this module does:
#   A KernelSU boot service (service.sh) waits for boot to complete, and if the
#   gadget is still unbound, replays the same kick the toggle does:
#     echo "" > UDC ; setprop sys.usb.config none ; setprop sys.usb.config sec_charging
#   That binds the UDC, so USB data works and "File transfer" is selectable the
#   normal way - no developer-options toggle needed. It only acts when the UDC is
#   empty, so a boot where USB already came up (e.g. adb active) is left untouched.
#
# This script only generates files and a zip. It downloads nothing. Install the
# resulting zip from the KernelSU-Next manager (Modules -> Install from storage)
# and reboot.
#
# Usage:
#   ./build_usb_fix_module.sh                 # build dist/usb-boot-fix/<id>.zip
#   ./build_usb_fix_module.sh --config mtp    # force File transfer at every boot
#                                             # instead of charge-only (see below)

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT_DIR="$ROOT_DIR/dist/usb-boot-fix"

MODULE_ID="un1ca_usb_boot_fix"
MODULE_VERSION="v1.1"
MODULE_VERSIONCODE="2"

# The config to assert when the gadget is found unbound. "sec_charging" restores
# normal behaviour (bound, charge-only, user picks File transfer). "mtp" makes
# File transfer come up automatically at every boot - more convenient but it
# exposes storage to any PC the moment the phone is unlocked while plugged in.
BIND_CONFIG="sec_charging"

while [ $# -gt 0 ]; do
    case "$1" in
        --config) BIND_CONFIG="${2:?--config needs a value}"; shift 2 ;;
        --config=*) BIND_CONFIG="${1#*=}"; shift ;;
        -h|--help) sed -n '2,40p' "$0"; exit 0 ;;
        *) echo "unknown argument: $1" >&2; exit 2 ;;
    esac
done

command -v zip >/dev/null || { echo "ERROR: 'zip' not found (apt install zip)" >&2; exit 1; }

WORK="$ROOT_DIR/.build/usb-fix-module"
rm -rf "$WORK"
mkdir -p "$WORK"

# --- module.prop ------------------------------------------------------------
cat > "$WORK/module.prop" <<EOF
id=${MODULE_ID}
name=UN1CA USB Gadget Boot Fix
version=${MODULE_VERSION}
versionCode=${MODULE_VERSIONCODE}
author=built by build_usb_fix_module.sh
description=Rebinds the USB gadget at boot so MTP/file transfer works without toggling USB debugging. Only acts when the gadget is left unbound at boot.
EOF

# --- service.sh (the boot kick) --------------------------------------------
# Written with BIND_CONFIG expanded in; everything else is literal (quoted
# heredoc) so no host variables leak into the on-device script.
{
cat <<EOF
#!/system/bin/sh
# UN1CA USB gadget boot fix - replays the "USB debugging toggle" kick once at
# boot, only when the gadget is still unbound. Generated by build_usb_fix_module.sh.
BIND_CONFIG="${BIND_CONFIG}"
EOF
cat <<'EOF'
MODDIR=${0%/*}
LOG="$MODDIR/usb_boot_fix.log"
exec >>"$LOG" 2>&1
echo "--- $(date 2>/dev/null) service.sh start (bind=$BIND_CONFIG)"

# Wait (up to ~120s) for Android to finish booting, so UsbDeviceManager has run
# its boot-time gadget setup before we look at the result.
i=0
while [ "$(getprop sys.boot_completed)" != "1" ] && [ "$i" -lt 120 ]; do
    sleep 1
    i=$((i + 1))
done
# Let the boot-time gadget setup settle.
sleep 5

G=/config/usb_gadget/g1
UDC_NODE="$G/UDC"

if [ ! -e "$UDC_NODE" ]; then
    echo "no $UDC_NODE present; nothing to do"
    exit 0
fi

bound="$(cat "$UDC_NODE" 2>/dev/null)"
echo "at boot: UDC='$bound' sys.usb.config='$(getprop sys.usb.config)' ffs.ready='$(getprop sys.usb.ffs.ready)'"

if [ -n "$bound" ]; then
    echo "gadget already bound to '$bound'; leaving it alone"
    exit 0
fi

echo "gadget unbound -> kicking (none -> $BIND_CONFIG)"
echo "" > "$UDC_NODE" 2>/dev/null
setprop sys.usb.config none
sleep 1
setprop sys.usb.config "$BIND_CONFIG"
sleep 1
echo "after kick: UDC='$(cat "$UDC_NODE" 2>/dev/null)' sys.usb.config='$(getprop sys.usb.config)'"
echo "--- done"
EOF
} > "$WORK/service.sh"
chmod 0755 "$WORK/service.sh"

# --- zip it up --------------------------------------------------------------
mkdir -p "$OUT_DIR"
ZIP="$OUT_DIR/${MODULE_ID}-${MODULE_VERSION}.zip"
rm -f "$ZIP"
( cd "$WORK" && zip -q -r -X "$ZIP" module.prop service.sh )

echo
echo "Built KernelSU module:"
echo "    $ZIP"
echo
echo "Contents:"
( cd "$WORK" && unzip -l "$ZIP" | sed 's/^/    /' )
echo
echo "Install: KernelSU-Next manager -> Modules -> Install from storage -> pick"
echo "the zip -> reboot. After reboot USB data works and 'File transfer' is"
echo "selectable without toggling USB debugging."
echo
echo "On-device log after boot:  /data/adb/modules/${MODULE_ID}/usb_boot_fix.log"
echo "Bind config this build asserts when unbound: ${BIND_CONFIG}"
