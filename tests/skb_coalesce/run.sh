#!/usr/bin/env bash
#
# run.sh - Build (and sign) the skb_try_coalesce() test module against the
# kernel tree, using the same toolchain as build.sh.
#
# This builds a .ko; it does not run anything here. The module runs the test
# in the kernel, so load it on a phone that is running the kernel you built:
#
#     cd kernel_samsung_sm7125
#     ./build_all.sh --device a52q ...      # build and flash that kernel
#     ./tests/skb_coalesce/run.sh           # build + sign the test module
#     adb push tests/skb_coalesce/skb_coalesce_test.ko /data/local/tmp/
#     adb shell su -c 'insmod /data/local/tmp/skb_coalesce_test.ko; \
#                      dmesg | grep skb_coalesce_test; \
#                      rmmod skb_coalesce_test 2>/dev/null'
#
# The module must match the running kernel:
#   - Build it against the same out/ that produced the flashed boot.img.
#   - out/certs/signing_key.pem is regenerated by a clean kernel build. The
#     flashed kernel embeds that key's public half, so sign the module with
#     the key from the same build and flash that same kernel. Rebuild the
#     kernel and you must re-sign and re-flash.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
OUT_DIR="$ROOT_DIR/out"
MODULE="$SCRIPT_DIR/skb_coalesce_test.ko"

die() {
    echo >&2
    echo "ERROR: $*" >&2
    exit 1
}

[ -f "$ROOT_DIR/build.sh" ] && [ -d "$OUT_DIR" ] ||
    die "run this from the kernel tree after a build; $OUT_DIR is missing
    Build the kernel first, e.g. ./build_all.sh --device a52q ..."
[ -f "$OUT_DIR/Module.symvers" ] ||
    die "$OUT_DIR has no Module.symvers; the kernel build did not finish"

# Mirror build.sh: prefer the tree's clang if it ships one, build with LLVM.
LLVM_BIN="$ROOT_DIR/llvm-aosp/bin"
[ -d "$LLVM_BIN" ] && export PATH="$LLVM_BIN:$PATH"

echo "Building $MODULE"
make -C "$ROOT_DIR" O="$OUT_DIR" ARCH=arm64 LLVM=1 M="$SCRIPT_DIR" modules
[ -f "$MODULE" ] || die "the module did not build"

# CONFIG_MODULE_SIG_FORCE=y: an unsigned module will not load. Sign it with
# the build's key when both the key and the tool are present.
key="$OUT_DIR/certs/signing_key.pem"
cert="$OUT_DIR/certs/signing_key.x509"
signer="$OUT_DIR/scripts/sign-file"
hash="$(sed -n 's/^CONFIG_MODULE_SIG_HASH="\(.*\)"$/\1/p' "$OUT_DIR/.config")"
if grep -qx 'CONFIG_MODULE_SIG_FORCE=y' "$OUT_DIR/.config"; then
    [ -x "$signer" ] && [ -f "$key" ] && [ -f "$cert" ] ||
        die "the kernel forces module signatures, but the signing key or sign-file is missing
    (expected $signer, $key, $cert from the kernel build)"
    "$signer" "${hash:-sha512}" "$key" "$cert" "$MODULE"
    echo "signed with the build's module key ($hash)"
fi

echo
echo "Built: $MODULE"
echo "Push it to a phone running this exact kernel and load it:"
echo "    adb push $MODULE /data/local/tmp/"
echo "    adb shell su -c 'insmod /data/local/tmp/skb_coalesce_test.ko; dmesg | grep skb_coalesce_test; rmmod skb_coalesce_test 2>/dev/null'"
echo
echo "All PASS (incl. the two [fix] lines) means the patch kept the normal"
echo "flow intact and its marker propagation works. insmod failing with the"
echo "[fix] lines marked FAIL means the running kernel is unpatched."
